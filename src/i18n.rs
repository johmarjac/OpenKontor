//! Languages of the interface and of printed documents.
//!
//! Texts are written in German in the code and looked up here for other languages.
//! To add a language: add a variant to `Lang`, a column to `TEXTS` and a case in `lookup`.

use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicU8, Ordering};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    De,
    En,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::De, Lang::En];

    /// The language's own name, for the language menu.
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::De => "Deutsch",
            Lang::En => "English",
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::De => "de",
            Lang::En => "en",
        }
    }

    pub fn from_code(code: &str) -> Lang {
        match code.trim().to_lowercase().as_str() {
            "en" | "english" | "englisch" => Lang::En,
            _ => Lang::De,
        }
    }

    /// The language the operating system is set to (for the first start).
    pub fn from_system() -> Lang {
        let v = std::env::var("LC_ALL")
            .or_else(|_| std::env::var("LC_MESSAGES"))
            .or_else(|_| std::env::var("LANG"))
            .unwrap_or_default();
        if v.to_lowercase().starts_with("en") { Lang::En } else { Lang::De }
    }
}

static CURRENT: AtomicU8 = AtomicU8::new(0);

/// Sets the interface language.
pub fn set_lang(lang: Lang) {
    CURRENT.store(lang as u8, Ordering::Relaxed);
}

pub fn lang() -> Lang {
    match CURRENT.load(Ordering::Relaxed) {
        1 => Lang::En,
        _ => Lang::De,
    }
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TEXTS.iter().chain(TEXTS_MORE).copied().collect())
}

fn reverse_table() -> &'static HashMap<&'static str, &'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TEXTS.iter().chain(TEXTS_MORE).map(|(de, en)| (*en, *de)).collect())
}

fn lookup(lang: Lang, de: &str) -> Option<&'static str> {
    match lang {
        Lang::De => None,
        Lang::En => table().get(de).copied(),
    }
}

/// A fixed text in the interface language.
pub fn t(de: &'static str) -> &'static str {
    lookup(lang(), de).unwrap_or(de)
}

/// A fixed text in a given language (for documents in the customer's language).
pub fn t_in(lang: Lang, de: &'static str) -> &'static str {
    lookup(lang, de).unwrap_or(de)
}

/// Any text (e.g. a message from the server) in the interface language, if it is known.
pub fn tr(de: &str) -> String {
    lookup(lang(), de).map(str::to_string).unwrap_or_else(|| de.to_string())
}

/// The German original of a translated text (texts already in German stay as they are).
pub fn to_german(text: &str) -> &str {
    reverse_table().get(text).copied().unwrap_or(text)
}

/// Fills `{}` placeholders of a translated template in order.
pub fn fill(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut out = String::new();
    let mut parts = template.split("{}");
    if let Some(first) = parts.next() {
        out.push_str(first);
    }
    for (i, part) in parts.enumerate() {
        if let Some(a) = args.get(i) {
            out.push_str(&a.to_string());
        }
        out.push_str(part);
    }
    out
}

/// `tf!("Seit {} Tagen überfällig", days)` – a translated template with values filled in.
#[macro_export]
macro_rules! tf {
    ($template:literal $(, $arg:expr)* $(,)?) => {
        $crate::i18n::fill($crate::i18n::t($template), &[$(&$arg as &dyn std::fmt::Display),*])
    };
}

